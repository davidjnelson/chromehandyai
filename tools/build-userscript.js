// Builds userscript/handy-ai-scripts.user.js: the whole extension in one file
// for userscript managers (Userscripts for Safari on iPhone, Tampermonkey, ...).
// Usage: node tools/build-userscript.js
'use strict';
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'manifest.json'), 'utf8'));

const parts = [
  'userscript/shim.js',
  'src/shared/funscript.js',
  'src/shared/motion.js',
  'src/shared/live.js',
  'src/shared/handy.js',
  'src/background.js',
  'src/content/store.js',
  'src/content/scanner.js',
  'src/content/live.js',
  'src/content/panel.js',
  'src/content/main.js',
];

const matches = manifest.content_scripts[0].matches;
const header = [
  '// ==UserScript==',
  '// @name         Handy AI Scripts',
  '// @namespace    https://github.com/davidjnelson/chromehandyai',
  `// @version      ${manifest.version}`,
  `// @description  ${manifest.description}`,
  ...matches.map((m) => `// @match        ${m}`),
  '// @grant        GM.xmlHttpRequest',
  '// @grant        GM.getValue',
  '// @grant        GM.setValue',
  '// @grant        GM.deleteValue',
  '// @grant        GM.listValues',
  '// @connect      handyfeeling.com',
  '// @connect      www.handyfeeling.com',
  '// @run-at       document-idle',
  '// @noframes',
  '// ==/UserScript==',
  '',
  '// Generated by tools/build-userscript.js from the extension sources. Do not edit by hand.',
  '',
].join('\n');

let body = '(function () {\n"use strict";\n';
for (const p of parts) {
  body += `\n// ---- ${p} ----\n` + fs.readFileSync(path.join(root, p), 'utf8') + '\n';
}
body += '})();\n';

const out = path.join(root, 'userscript', 'handy-ai-scripts.user.js');
fs.writeFileSync(out, header + body);
console.log('wrote', path.relative(root, out), (Buffer.byteLength(header + body) / 1024).toFixed(0) + ' KB');
